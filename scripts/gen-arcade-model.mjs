#!/usr/bin/env node
// Generates the ARCADE physics model (GAME_DESIGN 4.10) from the untouched stock files:
//   so101-arcade.xml  = so101.xml + one invisible, massless strike-hull capsule (radius 9 mm) in each of
//                       gripper, moving_jaw, camera_mount, wrist, lower_arm, sized to that link's collision geoms
//   arena-arcade.xml  = arena.xml referencing so101-arcade.xml + explicit hull and armour contact pairs (atlas × blaze only)
//
// Hulls carry contype = conaffinity = 0, so they never collide with anything automatically; the explicit <pair>
// elements make each atlas hull collide with each blaze hull and nothing else. That keeps a seat's hulls off its own
// links and off the table and cubes without <exclude>, which would also have silenced real self-collisions.
// Arcade also makes arm-vs-arm contact stiff. The stock grip contacts (solref 0.01) are soft on purpose, for grasping,
// so two servo-driven grippers ground 6-10 mm into each other and fast strikes sank the thin hulls 12 mm: the drawn
// meshes clipped. Explicit <pair>s between the two seats' ARMOR geoms (the jaw meshes and the big jaw, camera and
// gripper boxes) override the dynamic contact for exactly those pairs with the stock grip condim and friction but
// solref 0.005; grasping a cube still uses the stock contacts. (A stiffer solimp as well tipped bot balance: backlash
// vs deadband went from 4/12 to 1/12.) Three of those geoms are unnamed in so101.xml, so Arcade names them; the "arcade_" name prefix is the strip marker.
// Stripping the generated lines (stripArcadeRobot / stripArcadeArena) reproduces the stock files byte for byte.
//
// Usage: node scripts/gen-arcade-model.mjs [--check]
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const MODEL_DIR = path.join(root, "public", "models", "robotstudio_so101");
export const HULL_RADIUS_M = 0.009;
export const HULL_LINKS = ["lower_arm", "wrist", "gripper", "camera_mount", "moving_jaw_so101_v1"];
const LINK_ID = { lower_arm: "lower_arm", wrist: "wrist", gripper: "gripper", camera_mount: "camera_mount", moving_jaw_so101_v1: "moving_jaw" };
const ROBOT_MARK = "<!-- GENERATED by scripts/gen-arcade-model.mjs";
export const ARCADE_SOLREF = "0.005 1";
/** The stock grip contact (condim 6, friction 1 5e-3 5e-4) as a pair's five-number friction; only solref changes. */
const ARMOR_FRICTION = "1 1 5e-3 5e-4 5e-4";
/** Unnamed stock geoms that need a name, as [line prefix to match in order of appearance, name]. */
const ARMOR_NAMED = [
  ['<geom type="box" class="collision" pos="0 -0.000218 0.00095"', "arcade_grip_box"],
  ['<geom type="mesh" class="collision_gripper_mesh" pos="0 -0.000218 0.00095"', "arcade_fixed_jaw_mesh"],
  ['<geom type="mesh" class="collision_gripper_mesh" pos="0 0 0.0189"', "arcade_moving_jaw_mesh_a"],
  ['<geom type="mesh" class="collision_gripper_mesh" pos="0 0 0.0189"', "arcade_moving_jaw_mesh_b"],
];
export const ARMOR_GEOMS = ["fixed_jaw_box1", "fixed_jaw_box2", "moving_jaw_box1", "camera_box1", "camera_box2", ...ARMOR_NAMED.map(([, n]) => n)];
const ARENA_PAIRS_OPEN = "  <!-- strike hulls and armour pairs: GENERATED by scripts/gen-arcade-model.mjs -->";
const ARENA_PAIRS_CLOSE = "  <!-- /strike hulls and armour pairs -->";

/** so101-arcade.xml → so101.xml */
export function stripArcadeRobot(xml) {
  return xml.split("\n")
    .filter((l) => !l.includes('name="hull_') && !l.includes(ROBOT_MARK))
    .map((l) => l.replace(/<geom name="arcade_[a-z_]+" /, "<geom "))
    .join("\n");
}

/** arena-arcade.xml → arena.xml */
export function stripArcadeArena(xml) {
  const lines = xml.split("\n");
  const out = [];
  let skipping = false;
  for (const l of lines) {
    if (l === ARENA_PAIRS_OPEN) { skipping = true; continue; }
    if (l === ARENA_PAIRS_CLOSE) { skipping = false; continue; }
    if (!skipping) out.push(l);
  }
  return out.join("\n").replace('file="so101-arcade.xml"', 'file="so101.xml"');
}

function quatRotate(q, v) {
  const [w, x, y, z] = q;
  const n = Math.hypot(w, x, y, z);
  const a = w / n, b = x / n, c = y / n, d = z / n;
  const m = [
    a * a + b * b - c * c - d * d, 2 * (b * c - a * d), 2 * (b * d + a * c),
    2 * (b * c + a * d), a * a - b * b + c * c - d * d, 2 * (c * d - a * b),
    2 * (b * d - a * c), 2 * (c * d + a * b), a * a - b * b - c * c + d * d,
  ];
  return [m[0] * v[0] + m[1] * v[1] + m[2] * v[2], m[3] * v[0] + m[4] * v[1] + m[5] * v[2], m[6] * v[0] + m[7] * v[1] + m[8] * v[2]];
}

const fmt = (v) => (Math.abs(v) < 5e-7 ? "0" : Number(v.toFixed(6)).toString());

/** Hull capsules (body frame) for each target link, from the compiled robot's collision geoms. */
export async function measureHulls() {
  const { default: loadMujoco } = await import(pathToFileURL(path.join(root, "node_modules", "@mujoco", "mujoco", "mujoco.js")).href);
  const mujoco = await loadMujoco();
  const vfs = new mujoco.MjVFS();
  for (const f of readdirSync(path.join(MODEL_DIR, "assets"))) vfs.addBuffer(`assets/${f}`, readFileSync(path.join(MODEL_DIR, "assets", f)));
  const model = mujoco.MjModel.from_xml_string(readFileSync(path.join(MODEL_DIR, "so101.xml"), "utf8"), vfs);
  try {
    const hulls = {};
    for (const link of HULL_LINKS) {
      const body = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY.value, link);
      if (body < 0) throw new Error(`so101.xml has no body ${link}`);
      const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
      for (let g = 0; g < model.ngeom; g++) {
        if (model.geom_bodyid[g] !== body) continue;
        if ((model.geom_contype[g] | model.geom_conaffinity[g]) === 0) continue;
        const aabb = Array.from(model.geom_aabb.slice(g * 6, g * 6 + 6));
        const pos = Array.from(model.geom_pos.slice(g * 3, g * 3 + 3));
        const quat = Array.from(model.geom_quat.slice(g * 4, g * 4 + 4));
        for (let corner = 0; corner < 8; corner++) {
          const local = [0, 1, 2].map((k) => aabb[k] + ((corner >> k) & 1 ? aabb[3 + k] : -aabb[3 + k]));
          const r = quatRotate(quat, local);
          for (let k = 0; k < 3; k++) {
            const v = pos[k] + r[k];
            lo[k] = Math.min(lo[k], v); hi[k] = Math.max(hi[k], v);
          }
        }
      }
      if (!Number.isFinite(lo[0])) throw new Error(`${link} has no collision geoms to size a hull from`);
      const half = [0, 1, 2].map((k) => (hi[k] - lo[k]) / 2);
      const centre = [0, 1, 2].map((k) => (hi[k] + lo[k]) / 2);
      const axis = half.indexOf(Math.max(...half));
      const along = Math.max(0.0005, half[axis] - HULL_RADIUS_M);
      const from = centre.slice(), to = centre.slice();
      from[axis] -= along; to[axis] += along;
      hulls[link] = { from, to, lo, hi };
    }
    return hulls;
  } finally {
    model.delete();
    vfs.delete();
  }
}

export function buildArcadeRobot(so101Xml, hulls) {
  const lines = so101Xml.split("\n");
  const out = [];
  let named = 0;
  for (const line of lines) {
    if (named < ARMOR_NAMED.length && line.trimStart().startsWith(ARMOR_NAMED[named][0])) {
      out.push(line.replace("<geom ", `<geom name="${ARMOR_NAMED[named][1]}" `));
      named++;
      continue;
    }
    out.push(line);
    if (/^<mujoco model="so101">/.test(line)) {
      out.push(`  ${ROBOT_MARK} from so101.xml: adds strike hulls (hull_*). Do not edit; regenerate. -->`);
      continue;
    }
    const m = /^(\s*)<body name="([^"]+)"/.exec(line);
    if (m && hulls[m[2]]) {
      const h = hulls[m[2]];
      const indent = `${m[1]}  `;
      out.push(`${indent}<geom name="hull_${LINK_ID[m[2]]}" type="capsule" size="${HULL_RADIUS_M}" fromto="${[...h.from, ...h.to].map(fmt).join(" ")}" contype="0" conaffinity="0" group="4" mass="0" rgba="0 0 0 0"/>`);
    }
  }
  if (named !== ARMOR_NAMED.length) throw new Error(`so101.xml: found ${named} of ${ARMOR_NAMED.length} armour geoms to name`);
  return out.join("\n");
}

export function buildArcadeArena(arenaXml) {
  const pairs = [ARENA_PAIRS_OPEN, "  <contact>"];
  for (const a of HULL_LINKS) {
    for (const b of HULL_LINKS) {
      pairs.push(`    <pair geom1="atlas_hull_${LINK_ID[a]}" geom2="blaze_hull_${LINK_ID[b]}" condim="1" solref="${ARCADE_SOLREF}"/>`);
    }
  }
  for (const a of ARMOR_GEOMS) {
    for (const b of ARMOR_GEOMS) {
      pairs.push(`    <pair geom1="atlas_${a}" geom2="blaze_${b}" condim="6" friction="${ARMOR_FRICTION}" solref="${ARCADE_SOLREF}"/>`);
    }
  }
  pairs.push("  </contact>", ARENA_PAIRS_CLOSE);
  const swapped = arenaXml.replace('file="so101.xml"', 'file="so101-arcade.xml"');
  const closeAt = swapped.lastIndexOf("</mujoco>");
  if (closeAt < 0 || !swapped.includes('file="so101-arcade.xml"')) throw new Error("arena.xml is not in the expected shape");
  return `${swapped.slice(0, closeAt)}${pairs.join("\n")}\n${swapped.slice(closeAt)}`;
}

async function main() {
  const check = process.argv.includes("--check");
  const so101 = readFileSync(path.join(MODEL_DIR, "so101.xml"), "utf8");
  const arena = readFileSync(path.join(MODEL_DIR, "arena.xml"), "utf8");
  const hulls = await measureHulls();
  const robot = buildArcadeRobot(so101, hulls);
  const arcade = buildArcadeArena(arena);
  if (stripArcadeRobot(robot) !== so101 || stripArcadeArena(arcade) !== arena) {
    throw new Error("generated Arcade files do not strip back to the stock files");
  }
  const targets = [["so101-arcade.xml", robot], ["arena-arcade.xml", arcade]];
  let stale = 0;
  for (const [name, text] of targets) {
    const file = path.join(MODEL_DIR, name);
    let current = null;
    try { current = readFileSync(file, "utf8"); } catch { current = null; }
    if (current === text) { console.log(`ok       ${name}`); continue; }
    if (check) { console.error(`stale    ${name}`); stale++; continue; }
    writeFileSync(file, text);
    console.log(`wrote    ${name}`);
  }
  for (const link of HULL_LINKS) {
    const h = hulls[link];
    console.log(`hull ${LINK_ID[link].padEnd(12)} r ${HULL_RADIUS_M} m  fromto ${[...h.from, ...h.to].map(fmt).join(" ")}`);
  }
  if (stale) {
    console.error("Arcade model is out of date: run npm run gen:arcade-model");
    process.exit(1);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main().catch((err) => { console.error(err); process.exit(1); });
}
